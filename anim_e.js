  // углы конечностей в соседних кадрах приводятся к кратчайшему повороту
  const unwrap = K => { for (let i = 1; i < K.length; i++) ['L', 'A'].forEach(g => (K[i][g] || []).forEach((l, j) => { const pv = (K[i - 1][g] || [])[j]; if (!pv) return;
    ['u', 'f'].forEach(q => { if (l[q] == null || pv[q] == null) return; while (l[q] - pv[q] > 180) l[q] -= 360; while (l[q] - pv[q] < -180) l[q] += 360; }); })); return K; };


  // нога по точкам: от корня (таз) через колено к щиколотке, с укорочением сегментов (для вида спереди)
  const ang = (a, b) => Math.atan2(b[1] - a[1], b[0] - a[0]) * 180 / Math.PI;
  const dist = (a, b) => Math.hypot(b[0] - a[0], b[1] - a[1]);
  const legP = (root, knee, ank) => ({ u: ang(root, knee), s: dist(root, knee) / 42, f: ang(knee, ank), s2: dist(knee, ank) / 40 });
  // та же обратная кинематика, что в движке, но результат в углах (u, f): так конечность плавно интерполируется
  // между кадрами, где в соседнем кадре она задана углами
  const fkIK = (root, tgt, l1, l2, pref) => {
    const dx = tgt[0] - root[0], dy = tgt[1] - root[1], d0 = Math.hypot(dx, dy) || 0.001;
    const d = Math.min(l1 + l2 - 0.05, Math.max(Math.abs(l1 - l2) + 0.05, d0)), t = [root[0] + dx / d0 * d, root[1] + dy / d0 * d];
    const base = Math.atan2(dy, dx), c = Math.acos(Math.min(1, Math.max(-1, (l1 * l1 + d * d - l2 * l2) / (2 * l1 * d))));
    const js = [base + c, base - c].map(a => [root[0] + l1 * Math.cos(a), root[1] + l1 * Math.sin(a)]);
    const mid = [(root[0] + t[0]) / 2, (root[1] + t[1]) / 2], sc = j => (j[0] - mid[0]) * pref[0] + (j[1] - mid[1]) * pref[1];
    const j = sc(js[0]) >= sc(js[1]) ? js[0] : js[1];
    return { u: ang(root, j), f: ang(j, t) };
  };
  const armFK = (sh, tgt, pref) => fkIK(sh, tgt, 28, 26, pref || [-0.4, 1]);
  const legFK = (hip, tgt, pref) => fkIK(hip, tgt, 42, 40, pref || [1, 0]);
